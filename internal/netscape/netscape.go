// Package netscape reads and writes the HTML bookmark format understood by
// Chrome, Edge, Firefox and Arc.
package netscape

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"html"
	"io"
	"math"
	"os/exec"
	"strconv"
	"strings"
	"time"

	"arcm/internal/model"
)

const chromeEpochOffsetSeconds = int64(12622780800) // 1601-01-01 -> 1970-01-01

// ChromeTime converts Apple/CoreFoundation epoch seconds to Chrome's
// microseconds-since-1601 decimal string value as int64.
func ChromeTime(appleSeconds float64) int64 {
	if appleSeconds <= 0 {
		appleSeconds = float64(time.Now().Unix()) - 978307200
	}
	return int64(math.Round(appleSeconds*1_000_000)) + chromeEpochOffsetSeconds*1_000_000
}

type Group struct {
	Title string
	Nodes []*model.Node
}

func Export(groups []Group, w io.Writer) error {
	var b strings.Builder
	b.WriteString("<!DOCTYPE NETSCAPE-Bookmark-file-1>\n")
	b.WriteString("<!-- Generated by arcm. Do not edit by hand. -->\n")
	b.WriteString("<META HTTP-EQUIV=\"Content-Type\" CONTENT=\"text/html; charset=UTF-8\">\n")
	b.WriteString("<TITLE>arcm Bookmarks</TITLE>\n")
	b.WriteString("<H1>arcm Bookmarks</H1>\n")
	b.WriteString("<DL><p>\n")
	for _, g := range groups {
		if g.Title == "" {
			for _, n := range g.Nodes {
				emit(&b, n, 1)
			}
			continue
		}
		fmt.Fprintf(&b, "    <DT><H3 ADD_DATE=\"%d\" LAST_MODIFIED=\"0\">%s</H3>\n", ChromeTime(0), html.EscapeString(g.Title))
		b.WriteString("    <DL><p>\n")
		for _, n := range g.Nodes {
			emit(&b, n, 2)
		}
		b.WriteString("    </DL><p>\n")
	}
	b.WriteString("</DL><p>\n")
	_, err := io.WriteString(w, b.String())
	return err
}

func emit(b *strings.Builder, n *model.Node, depth int) {
	pad := strings.Repeat("    ", depth)
	if n.Kind == model.Folder {
		fmt.Fprintf(b, "%s<DT><H3 ADD_DATE=\"%d\" LAST_MODIFIED=\"0\">%s</H3>\n", pad, ChromeTime(n.Created), html.EscapeString(n.Title))
		fmt.Fprintf(b, "%s<DL><p>\n", pad)
		for _, c := range n.Children {
			emit(b, c, depth+1)
		}
		fmt.Fprintf(b, "%s</DL><p>\n", pad)
		return
	}
	fmt.Fprintf(b, "%s<DT><A HREF=\"%s\" ADD_DATE=\"%d\" LAST_MODIFIED=\"0\">%s</A>\n", pad, html.EscapeString(n.URL), ChromeTime(n.Created), html.EscapeString(n.Title))
}

// Parse converts Netscape bookmark HTML into a tree. The HTML is normalized
// by libxml2's xmllint first, so unquoted attributes, entities and comments
// are handled by a real HTML parser instead of regular expressions.
func Parse(r io.Reader) ([]*model.Node, error) {
	cmd := exec.Command("xmllint", "--html", "--xmlout", "--recover", "-")
	cmd.Stdin = r
	var normalized, diagnostics bytes.Buffer
	cmd.Stdout = &normalized
	cmd.Stderr = &diagnostics
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("xmllint failed: %w: %s", err, strings.TrimSpace(diagnostics.String()))
	}
	if strings.TrimSpace(diagnostics.String()) != "" {
		return nil, fmt.Errorf("invalid bookmark HTML: %s", strings.TrimSpace(diagnostics.String()))
	}
	if normalized.Len() == 0 {
		return nil, fmt.Errorf("invalid bookmark HTML: empty document")
	}
	return parseXHTML(&normalized)
}

func parseXHTML(r io.Reader) ([]*model.Node, error) {
	dec := xml.NewDecoder(r)
	root := &model.Node{Kind: model.Folder}
	stack := []*model.Node{root}
	var pending *model.Node
	var text strings.Builder
	var mode string
	var link *model.Node
	var date float64
	sawDL := false

	for {
		tok, err := dec.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, fmt.Errorf("parse normalized bookmark HTML: %w", err)
		}
		switch t := tok.(type) {
		case xml.StartElement:
			switch strings.ToLower(t.Name.Local) {
			case "dl":
				sawDL = true
				if pending != nil {
					stack = append(stack, pending)
					pending = nil
				}
			case "h3":
				pending = nil
				mode = "h3"
				text.Reset()
				date = chromeTimeToApple(attr(t, "add_date"))
			case "a":
				pending = nil
				mode = "a"
				text.Reset()
				link = &model.Node{
					Kind:    model.Link,
					URL:     strings.TrimSpace(attr(t, "href")),
					Created: chromeTimeToApple(attr(t, "add_date")),
				}
			}
		case xml.CharData:
			if mode != "" {
				text.Write(t)
			}
		case xml.EndElement:
			switch strings.ToLower(t.Name.Local) {
			case "h3":
				title := clean(text.String())
				if title == "" {
					title = "(untitled folder)"
				}
				n := &model.Node{Kind: model.Folder, Title: title, Created: date}
				stack[len(stack)-1].Children = append(stack[len(stack)-1].Children, n)
				pending = n
				mode = ""
			case "a":
				if link != nil {
					title := clean(text.String())
					if title == "" {
						title = link.URL
					}
					link.Title = title
					stack[len(stack)-1].Children = append(stack[len(stack)-1].Children, link)
					link = nil
					mode = ""
				}
			case "dl":
				if len(stack) > 1 {
					stack = stack[:len(stack)-1]
				}
			}
		}
	}
	if !sawDL {
		return nil, fmt.Errorf("invalid bookmark HTML: no DL list")
	}
	return root.Children, nil
}

func attr(t xml.StartElement, name string) string {
	for _, a := range t.Attr {
		if strings.EqualFold(a.Name.Local, name) {
			return a.Value
		}
	}
	return ""
}

func chromeTimeToApple(value string) float64 {
	micros, err := strconv.ParseInt(strings.TrimSpace(value), 10, 64)
	if err != nil || micros <= 0 {
		return 0
	}
	return float64(micros)/1_000_000 - float64(chromeEpochOffsetSeconds)
}

func clean(s string) string {
	return strings.TrimSpace(s)
}
